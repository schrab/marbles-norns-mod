#!/usr/bin/env python3
"""Extract marbles lookup tables from the vendored C++ into data/marbles_tables.lua.

lut_logit and lut_raised_cosine are literal float arrays in
reference/eurorack/marbles/resources.cc; parsing them out verbatim (rather
than regenerating them from formulas) guarantees byte-identical values.
Emitted as 0-based Lua tables -- every call site indexes them with a raw
C++ array subscript (lut_logit[i], and stmlib::Interpolate(lut_raised_cosine,
x, 256.0f) which maps table[j] to key j).
"""
import re
import pathlib

ROOT = pathlib.Path(__file__).resolve().parent.parent
SRC = ROOT / "reference" / "eurorack" / "marbles" / "resources.cc"
OUT = ROOT / "data" / "marbles_tables.lua"

text = SRC.read_text()

def extract(name):
    m = re.search(r"const float %s\[\] = \{(.*?)\};" % name, text, re.S)
    values = [v for v in re.findall(r"[-+0-9.eE]+", m.group(1))]
    return values

tables = {name: extract(name) for name in ("lut_raised_cosine", "lut_logit")}

lines = [
    "-- GENERATED by tools/extract_marbles_tables.py -- do not edit by hand.",
    "-- Verbatim float arrays from reference/eurorack/marbles/resources.cc",
    "-- (lut_raised_cosine: 257 entries, lut_logit: 257 entries). 0-based keys",
    "-- mirror the C++ array subscripts at every call site.",
    "return {",
]
for name, values in tables.items():
    lines.append("  %s = {" % name)
    for i, v in enumerate(values):
        lines.append("    [%d] = %s," % (i, v))
    lines.append("  },")
lines.append("}")
OUT.write_text("\n".join(lines) + "\n")
print("wrote", OUT)
for name, values in tables.items():
    print(name, len(values), "entries; first", values[0], "last", values[-1])
